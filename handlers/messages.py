def gender_tokens(gender: Gender) -> Dict[str, str]:
    """Набор словоформ под пол. Нейтральные — без корявых '(а)'."""
    if gender == "male":
        return {
            "decided": "решил",
            "Decided": "Решил",
            "ready": "готов",
            "Ready": "Готов",
            "returned": "вернулся",
            "wrote": "написал",
            "forgot": "забыл",
        }
    if gender == "female":
        return {
            "decided": "решила",
            "Decided": "Решила",
            "ready": "готова",
            "Ready": "Готова",
            "returned": "вернулась",
            "wrote": "написала",
            "forgot": "забыла",
        }
    # unknown
    return {
        "decided": "решил",
        "Decided": "Решил",
        "ready": "готов",
        "Ready": "Готов",
        "returned": "снова здесь",  # нейтрально и естественно
        "wrote": "написал",
        "forgot": "забыл",
    }

